    public static func englishBundle(in baseBundle: Bundle) -> Bundle {
        if let path = baseBundle.path(forResource: "en", ofType: "lproj"),
           let b = Bundle(path: path) {
            return b
        }
        return baseBundle
    }

    public static func localizedBundle(in baseBundle: Bundle, for language: AppLanguage? = nil) -> Bundle {
        let rawLang = language ?? NXThemeManager.shared.currentLanguage
        let lang = rawLang == .system ? AppLanguage.resolve() : rawLang
        let candidates: [String]
        switch lang {
        case .ptBR: candidates = ["pt-BR", "pt", "en"]
        case .ptPT: candidates = ["pt-PT", "pt", "en"]
        case .zhHans: candidates = ["zh-Hans", "zh", "en"]
        case .zhHant: candidates = ["zh-Hant", "zh-HK", "zh-TW", "zh-Hans", "en"]
        default: candidates = [lang.rawValue, "en"]
        }
        for code in candidates {
            if let path = baseBundle.path(forResource: code, ofType: "lproj"),
               let b = Bundle(path: path) {
                return b
            }
        }
        return baseBundle
    }

    public static func translate(_ text: String, language: AppLanguage? = nil) -> String {
        let rawLang = language ?? NXThemeManager.shared.currentLanguage
        let lang = rawLang == .system ? AppLanguage.resolve() : rawLang
        if lang == .en || text.isEmpty { return text }

        if let dict = table[lang], let translated = dict[text] {
            return translated
        }
        if lang == .ptPT, let translated = ptBR[text] {
            return translated
        }
        if lang == .zhHant, let translated = zhHans[text] {
            return translated
        }
        return translateDynamic(text, language: lang)
    }

    private static func translateDynamic(_ text: String, language: AppLanguage) -> String {
        // 1. "X (from Settings)"
        if text.hasSuffix(" (from Settings)") {
            let base = String(text.dropLast(" (from Settings)".count))
            let trBase = translate(base, language: language)
            let suffix = translate("(from Settings)", language: language)
            return "\(trBase) \(suffix)"
        }
        // 2. "Title ID X"
        if text.hasPrefix("Title ID ") {
            let id = String(text.dropFirst("Title ID ".count))
            let prefix = translate("Title ID", language: language)
            return "\(prefix) \(id)"
        }
        // 3. "Version X"
        if text.hasPrefix("Version ") {
            let ver = String(text.dropFirst("Version ".count))
            let prefix = translate("Version", language: language)
            return "\(prefix) \(ver)"
        }
        // 4. "Delete “X”?"
        if text.hasPrefix("Delete “") && text.hasSuffix("”?") {
            let inner = String(text.dropFirst("Delete “".count).dropLast("”?".count))
            let delWord = translate("Delete", language: language)
            return "\(delWord) “\(inner)”?"
        }
        // 5. "Quit X?"
        if text.hasPrefix("Quit ") && text.hasSuffix("?") {
            let inner = String(text.dropFirst("Quit ".count).dropLast(1))
            let quitWord = translate("Quit", language: language)
            return "\(quitWord) \(inner)?"
        }
        // 6. "Player X"
        if text.hasPrefix("Player ") {
            let num = String(text.dropFirst("Player ".count))
            let playerWord = translate("Player", language: language)
            return "\(playerWord) \(num)"
        }
        // 7. "Played X"
        if text.hasPrefix("Played ") && text != "Played today" && text != "Played yesterday" {
            let when = String(text.dropFirst("Played ".count))
            let playedWord = translate("Played", language: language)
            return "\(playedWord) \(when)"
        }
        // 8. "X of Y" (e.g. "1 of 4")
        let parts = text.components(separatedBy: " of ")
        if parts.count == 2, Int(parts[0]) != nil, Int(parts[1]) != nil {
            let ofWord = translate("of", language: language)
            return "\(parts[0]) \(ofWord) \(parts[1])"
        }
        // 9. "Put every control of the X layout back in its built-in place?"
        if text.hasPrefix("Put every control of the ") && text.hasSuffix(" layout back in its built-in place?") {
            return translate("Put every control of the layout back in its built-in place?", language: language)
        }
        return text
    }

